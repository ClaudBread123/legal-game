export const FL_PROPOSAL_SETTLEMENT = `
PROPOSALS FOR SETTLEMENT — §768.79, FLORIDA STATUTES AND RULE 1.442

PURPOSE:
A party may serve a proposal for settlement (offer of judgment) at any time more than 90 days after the complaint is filed.

FEE-SHIFTING MECHANISM:
If a defendant serves a PFS and the judgment obtained by the plaintiff is at least 25% LESS than the PFS amount, the defendant is entitled to recover reasonable attorney's fees from the date of the PFS.

If a plaintiff serves a PFS and the judgment is at least 25% MORE than the PFS amount, the plaintiff is entitled to recover reasonable attorney's fees.

REQUIREMENTS FOR VALID PFS (Rule 1.442):
1. Must be in writing
2. Must state it is being made pursuant to §768.79 and Rule 1.442
3. Must name the party making the offer and the party to whom it is made
4. Must state with particularity any relevant conditions
5. Must state the total amount of the offer
6. Must be served no earlier than 90 days after filing of the complaint and no later than 45 days before trial

STRATEGIC NOTE: A well-timed PFS is a powerful fee-shifting weapon. In governmental defense, a PFS at or near the sovereign immunity cap can create significant fee exposure for plaintiff if they reject it and fail to recover more at trial.
`

export function getLegalContextForAction(actionId, caseObject) {
  const sections = []

  // Always include core §768.28 for governmental defense cases
  sections.push(FL_768_28_FULL)

  // Reinforce for actions that directly analyze §768.28 issues
  if (['motion_to_dismiss', 'check_presuit_notice', 'check_statute_of_limitations', 'initial_evaluation'].includes(actionId)) {
    sections.push(FL_768_28_FULL)
  }

  // Add §1983/removal context if case has federal claims
  if (caseObject?.claimsAsserted?.some(c =>
    c.includes('1983') || c.includes('federal') || c.includes('Civil Rights')
  )) {
    sections.push(FL_1983_REMOVAL)
  }

  // Add discovery rules for discovery actions
  if (['written_discovery', 'respond_to_discovery', 'take_plaintiff_depo', 'motion_summary_judgment'].includes(actionId)) {
    sections.push(FL_DISCOVERY_RULES)
  }

  // Add Bert Harris for property rights cases
  if (caseObject?.caseType === 'bert_harris') {
    sections.push(FL_BERT_HARRIS)
  }

  // Add employment/admin exhaustion for employment cases
  if (caseObject?.caseType === 'employment' || caseObject?.claimsAsserted?.some(c =>
    c.includes('Whistle') || c.includes('FCHR') || c.includes('discrimination')
  )) {
    sections.push(FL_EMPLOYMENT_ADMIN)
  }

  // Add PFS context for proposal for settlement action
  if (actionId === 'evaluate_pfs') {
    sections.push(FL_PROPOSAL_SETTLEMENT)
  }

  // Deduplicate (Set preserves insertion order)
  return [...new Set(sections)].join('\n\n---\n\n')
}
