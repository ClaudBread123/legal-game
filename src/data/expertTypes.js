export function getRecommendedExpertTypes(caseObject) {
  const claims = (caseObject.claimsAsserted || []).join(' ').toLowerCase()
  const facts = (caseObject.factScenario || '').toLowerCase()
  const combined = claims + ' ' + facts

  return EXPERT_TYPES.filter(et =>
    et.applicableKeywords.some(kw => combined.includes(kw.toLowerCase())) ||
    et.applicableCaseTypes.includes(caseObject.caseType)
  ).map(et => et.id)
}

